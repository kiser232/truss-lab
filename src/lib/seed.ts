function unknownPassword(): string {
  return hashPassword(randomBytes(18).toString("hex"));
}

export function buildSeed(): Database {
  let nextCommentId = 1;
  const posts: Post[] = SEED.map((item, index) => ({
    id: index + 1,
    title: item.title,
    content: item.content,
    author: item.author,
    passwordHash: unknownPassword(),
    category: item.category,
    isNotice: Boolean(item.isNotice),
    views: item.views,
    upvotes: item.upvotes,
    downvotes: item.downvotes,
    createdAt: item.createdAt,
    comments: (item.comments ?? []).map((comment) => ({
      id: nextCommentId++,
      author: comment.author,
      content: comment.content,
      passwordHash: unknownPassword(),
      createdAt: comment.createdAt,
    })),
  }));

  return {
    nextPostId: posts.length + 1,
    nextCommentId,
    posts,
    votes: {},
    seen: {},
  };
}
